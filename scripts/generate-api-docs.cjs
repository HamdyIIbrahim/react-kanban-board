#!/usr/bin/env node
/**
 * Generates docs/API.md from the TypeScript source so the public API
 * reference cannot drift from the actual types. Run via `npm run docs`.
 *
 * It reads the exported interfaces / type aliases (and KanbanBoardProps)
 * directly out of src/index.tsx and renders markdown tables. Descriptions
 * come from leading or trailing `//` comments on each member.
 */
const fs = require("fs");
const path = require("path");
const ts = require("typescript");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "src", "index.tsx");
const OUT = path.join(ROOT, "docs", "API.md");

// Order in which types are documented.
const INTERFACES = [
  ["KanbanBoardProps", "KanbanBoard props"],
  ["Column", "Column"],
  ["Card", "Card"],
  ["DropPosition", "DropPosition"],
  ["FilterConfig", "FilterConfig"],
  ["FilterOption", "FilterOption"],
];
const TYPE_ALIASES = [["DeleteConfirmation", "DeleteConfirmation"]];

const fullText = fs.readFileSync(SRC, "utf8");
const sf = ts.createSourceFile(SRC, fullText, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);

const cleanComment = (raw) =>
  raw
    .replace(/^\/\*\*?/, "")
    .replace(/\*\/$/, "")
    .replace(/^\/\//, "")
    .split("\n")
    .map((l) => l.replace(/^\s*\*?\s?/, "").replace(/^\/\/\s?/, "").trim())
    .filter(Boolean)
    .join(" ")
    .trim();

const getDescription = (node) => {
  const trailing = ts.getTrailingCommentRanges(fullText, node.end) || [];
  if (trailing.length) {
    return cleanComment(fullText.slice(trailing[0].pos, trailing[0].end));
  }
  // Join all leading comment lines (multi-line `//` blocks describe one member).
  const leading = ts.getLeadingCommentRanges(fullText, node.getFullStart()) || [];
  if (leading.length) {
    return leading
      .map((r) => cleanComment(fullText.slice(r.pos, r.end)))
      .filter(Boolean)
      .join(" ")
      .trim();
  }
  return "";
};

// Normalize a type string to a single line and escape markdown pipes.
const normalizeType = (t) =>
  t.replace(/\s*\n\s*/g, " ").replace(/\s{2,}/g, " ").replace(/\|/g, "\\|").trim();

const mdEscape = (s) => s.replace(/\|/g, "\\|");

const findDeclaration = (name) => {
  let found = null;
  sf.forEachChild((node) => {
    if (
      (ts.isInterfaceDeclaration(node) || ts.isTypeAliasDeclaration(node)) &&
      node.name.text === name
    ) {
      found = node;
    }
  });
  return found;
};

const renderInterface = (name, heading) => {
  const decl = findDeclaration(name);
  if (!decl || !ts.isInterfaceDeclaration(decl)) {
    throw new Error(`Interface not found: ${name}`);
  }
  const rows = decl.members
    .filter(ts.isPropertySignature)
    .map((m) => {
      const propName = m.name.getText(sf);
      const optional = !!m.questionToken;
      const type = m.type ? normalizeType(m.type.getText(sf)) : "unknown";
      const desc = mdEscape(getDescription(m));
      return `| \`${propName}\` | \`${type}\` | ${optional ? "No" : "Yes"} | ${desc} |`;
    });
  return [
    `### ${heading}`,
    "",
    "| Property | Type | Required | Description |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
};

const renderTypeAlias = (name, heading) => {
  const decl = findDeclaration(name);
  if (!decl || !ts.isTypeAliasDeclaration(decl)) {
    throw new Error(`Type alias not found: ${name}`);
  }
  const def = normalizeType(decl.type.getText(sf));
  const desc = getDescription(decl);
  return [
    `### ${heading}`,
    "",
    desc ? `${desc}\n` : "",
    "```ts",
    `type ${name} = ${def.replace(/\\\|/g, "|")};`,
    "```",
    "",
  ].join("\n");
};

const parts = [
  "<!-- AUTO-GENERATED by scripts/generate-api-docs.cjs — do not edit by hand. Run `npm run docs`. -->",
  "",
  "# API Reference",
  "",
  "This file is generated from the TypeScript types in `src/index.tsx` and is",
  "the authoritative reference for the public API. Regenerate with `npm run docs`.",
  "",
];

for (const [name, heading] of INTERFACES) parts.push(renderInterface(name, heading));
for (const [name, heading] of TYPE_ALIASES) parts.push(renderTypeAlias(name, heading));

const output = parts.join("\n").replace(/\n{3,}/g, "\n\n").replace(/\s+$/, "") + "\n";

fs.mkdirSync(path.dirname(OUT), { recursive: true });

if (process.argv.includes("--check")) {
  const existing = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (existing !== output) {
    console.error(
      "docs/API.md is out of date. Run `npm run docs` and commit the result."
    );
    process.exit(1);
  }
  console.log("docs/API.md is up to date.");
} else {
  fs.writeFileSync(OUT, output);
  console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}
